#!/usr/bin/env node
/**
 * Writes REVIEW.md and benchmarks/suites/change-records.json from:
 * - manifest.json (the imported guides),
 * - review-data.json (reviewer decisions: flagged guides and "no task" reasons),
 * - benchmarks/tasks/cr-* (tasks whose first `guides:` entry is a change-record guide).
 * A record whose core lower bound is above the benchmark's base app is "needs newer core".
 * Makes no network requests and does not touch guides/.
 *
 * Usage: node import/change-records/review.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const BASE_CORE = '11.4.13';
const manifest = JSON.parse(fs.readFileSync(path.join(here, 'manifest.json'), 'utf8'));
const data = JSON.parse(fs.readFileSync(path.join(here, 'review-data.json'), 'utf8'));
const tasksDir = path.join(root, 'benchmarks', 'tasks');

const verNum = (v) => v.split('.').map(Number).reduce((a, n, i) => a + n * 1000 ** (2 - i), 0);
const lowerBound = (c) => {
  const all = [...c.matchAll(/(\d+)\.(\d+)(?:\.(\d+))?/g)].map((m) => `${m[1]}.${m[2]}.${m[3] ?? 0}`);
  return all.sort((a, b) => verNum(a) - verNum(b))[0];
};
const needsNewer = (g) => verNum(lowerBound(g.drupalCore)) > verNum(BASE_CORE);

const byName = new Map(manifest.guides.map((g) => [g.path.split('/').pop(), g]));
const tasks = new Map();
for (const id of fs.readdirSync(tasksDir).filter((d) => d.startsWith('cr-')).sort()) {
  const f = path.join(tasksDir, id, 'task.md');
  if (!fs.existsSync(f)) continue;
  const fm = fs.readFileSync(f, 'utf8').split('\n---')[0];
  const first = (fm.match(/^guides:\s*\[([^\],]+)/m) || [])[1]?.trim();
  const g = byName.get(first);
  if (!g) throw new Error(`${id}: first guide "${first}" is not a change-record guide`);
  if (!tasks.has(g.nid)) tasks.set(g.nid, []);
  tasks.get(g.nid).push(id);
}

const rows = [];
const counts = { task: 0, noTask: 0, newer: 0, untriaged: 0 };
for (const g of [...manifest.guides].sort((a, b) => a.category.localeCompare(b.category) || Number(a.nid) - Number(b.nid))) {
  let outcome;
  if (tasks.has(g.nid)) {
    outcome = tasks.get(g.nid).map((t) => `task \`${t}\``).join(', ');
    counts.task++;
  } else if (needsNewer(g)) {
    outcome = `needs newer core (${g.drupalCore})`;
    counts.newer++;
  } else if (data.noTask[g.nid]) {
    outcome = `no task: ${data.noTask[g.nid]}`;
    counts.noTask++;
  } else {
    outcome = 'not yet triaged';
    counts.untriaged++;
  }
  rows.push({ g, outcome });
}

const esc = (s) => s.replace(/\|/g, '\\|');
const link = (g) => `[${g.nid}](${g.url})`;
const out = [];
out.push('# Change record import: review', '');
out.push(`Generated by \`review.mjs\` from \`manifest.json\`, \`review-data.json\` and the \`cr-*\` tasks in \`benchmarks/tasks/\`. Edit \`review-data.json\` and rerun; do not edit this file by hand.`, '');
out.push('## Summary', '');
out.push(`- Imported guides: ${manifest.guides.length}. Benchmark base app: Drupal ${BASE_CORE}.`);
out.push(`- Records with a calibrated benchmark task: ${counts.task} (${[...tasks.values()].flat().length} tasks, suite \`change-records\`).`);
out.push(`- No task: ${counts.noTask}. Needs newer core than ${BASE_CORE}: ${counts.newer}. Not yet triaged: ${counts.untriaged}.`);
out.push(`- Flagged as not useful to a coding agent: ${Object.keys(data.flagged).length} (kept, not deleted).`, '');
out.push('## Import review', '');
for (const line of data.importReview) out.push(`- ${line}`);
out.push('', '## Guides flagged as not useful to a coding agent', '');
out.push('These guides stay in `guides/`. A reviewer may decide to exclude them from search later.', '');
out.push('| Record | Title | Guide | Reason |', '|---|---|---|---|');
for (const [nid, reason] of Object.entries(data.flagged).sort()) {
  const g = manifest.guides.find((x) => x.nid === nid);
  out.push(`| ${link(g)} | ${esc(g.title)} | \`${g.path.replace(/^guides\//, '')}\` | ${esc(reason)} |`);
}
out.push('', '## Every record', '');
out.push('"Needs newer core" means the record was introduced after the base app\'s core version, so a task cannot calibrate on it yet.', '');
let cat = '';
for (const { g, outcome } of rows) {
  if (g.category !== cat) {
    cat = g.category;
    out.push('', `### ${cat}`, '', '| Record | Title | Core | Outcome |', '|---|---|---|---|');
  }
  out.push(`| ${link(g)} | ${esc(g.title)} | \`${esc(g.drupalCore)}\` | ${esc(outcome)} |`);
}
fs.writeFileSync(path.join(here, 'REVIEW.md'), out.join('\n') + '\n');

const suite = {
  name: 'change-records',
  description: 'Tasks built from Drupal core change records for 11.x (see import/change-records/REVIEW.md). Each prompt describes the behavior without naming the API the record introduces.',
  tasks: [...tasks.values()].flat().sort(),
};
fs.writeFileSync(path.join(root, 'benchmarks', 'suites', 'change-records.json'), JSON.stringify(suite, null, 2) + '\n');
console.log(counts, `${suite.tasks.length} tasks in suite`);
